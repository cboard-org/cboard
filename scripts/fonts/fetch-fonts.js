#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const FONTS = [
  { id: 'andika', family: 'Andika', weights: [400, 700], ofl: 'andika' },
  { id: 'chilanka', family: 'Chilanka', weights: [400], ofl: 'chilanka' },
  {
    id: 'comic-neue',
    family: 'Comic Neue',
    weights: [400, 700],
    ofl: 'comicneue'
  },
  { id: 'hind', family: 'Hind', weights: [400, 700], ofl: 'hind' },
  {
    id: 'indie-flower',
    family: 'Indie Flower',
    weights: [400],
    ofl: 'indieflower'
  },
  { id: 'lexend', family: 'Lexend', weights: [400, 700], ofl: 'lexend' },
  {
    id: 'montserrat',
    family: 'Montserrat',
    weights: [400, 700],
    ofl: 'montserrat'
  },
  { id: 'nunito', family: 'Nunito', weights: [400, 700], ofl: 'nunito' },
  { id: 'oswald', family: 'Oswald', weights: [400, 700], ofl: 'oswald' }
];

const VERSION = '5.3.0';
const SKIPPED_SUBSETS = ['emoji', 'math', 'symbols'];
const OUT_DIR = path.join(__dirname, '..', '..', 'src', 'fonts');
const API = 'https://api.fontsource.org/v1/fonts/';
const CDN = 'https://cdn.jsdelivr.net/fontsource/fonts/';
const OFL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/';

async function get(url) {
  const res = await fetch(url);
  if (res.status !== 200) {
    throw new Error(`GET ${url} → HTTP ${res.status}`);
  }
  return res;
}

async function fetchFont(font) {
  const meta = await (await get(API + font.id)).json();
  if (meta.npmVersion !== VERSION) {
    console.warn(
      `${font.id}: Fontsource is at ${meta.npmVersion}, downloading pinned ${VERSION}`
    );
  }

  const dir = path.join(OUT_DIR, font.id);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });

  const rules = [];
  for (const weight of font.weights) {
    const variant = meta.variants[weight] && meta.variants[weight].normal;
    if (!variant) {
      throw new Error(`${font.id}: no normal style for weight ${weight}`);
    }
    const subsets = Object.keys(variant)
      .filter((subset) => !SKIPPED_SUBSETS.includes(subset))
      .sort();
    for (const subset of subsets) {
      const range = meta.unicodeRange[subset];
      if (!range) {
        throw new Error(`${font.id}: no unicode-range for ${subset}`);
      }
      const file = `${font.id}-${subset}-${weight}.woff2`;
      const url = `${CDN}${font.id}@${VERSION}/${subset}-${weight}-normal.woff2`;
      const data = Buffer.from(await (await get(url)).arrayBuffer());
      fs.writeFileSync(path.join(dir, file), data);
      rules.push({ family: font.family, weight, subset, file, range });
    }
  }

  const license = await (await get(`${OFL}${font.ofl}/OFL.txt`)).text();
  fs.writeFileSync(path.join(dir, 'OFL.txt'), license);

  return rules;
}

function fontFace({ family, weight, file, range }, id) {
  return [
    '@font-face {',
    `  font-family: '${family}';`,
    '  font-style: normal;',
    `  font-weight: ${weight};`,
    '  font-display: swap;',
    `  src: url('./${id}/${file}') format('woff2');`,
    `  unicode-range: ${range};`,
    '}'
  ].join('\n');
}

async function main() {
  const fonts = [...FONTS].sort((a, b) => a.family.localeCompare(b.family));
  const blocks = [];
  const versions = [];
  for (const font of fonts) {
    const rules = await fetchFont(font);
    versions.push(`${font.family} ${VERSION}`);
    rules
      .sort((a, b) => a.weight - b.weight || a.subset.localeCompare(b.subset))
      .forEach((rule) => blocks.push(fontFace(rule, font.id)));
    console.log(`${font.family}: ${rules.length} files`);
  }

  const header = `/* Generated by scripts/fonts/fetch-fonts.js from Fontsource: ${versions.join(
    ', '
  )} */`;
  fs.writeFileSync(
    path.join(OUT_DIR, 'fonts.css'),
    `${header}\n\n${blocks.join('\n\n')}\n`
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
